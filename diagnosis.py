# ============ MBTI解析 ============

def parse_mbti(mbti_str: str) -> tuple[bool, bool]:
    s = mbti_str.strip().upper()
    intuitive = "N" in s
    judging = "J" in s
    return intuitive, judging

def fallback_to_axes(answer: str) -> tuple[bool, bool]:
    if answer.upper() == "A":
        return True, False
    else:
        return False, True

# ============ スコア計算 ============

def calc_risk(q2: str, q3: str, q4: str) -> int:
    R = 0
    R += {"A": 0, "B": 1, "C": 2, "D": 3}.get(q2.upper(), 0)
    R += {"A": 0, "B": 1, "C": 1, "D": 2}.get(q3.upper(), 0)
    if q4.upper() == "A":
        R = max(0, R - 2)
    elif q4.upper() == "B":
        R = max(0, R - 1)
    return R

def calc_surplus(q5: str) -> str:
    return {"A": "low", "B": "mid", "C": "high"}.get(q5.upper(), "low")

# ============ タイプ判定 ============

def determine_type(intuitive: bool, judging: bool, R: int, surplus: str) -> str:
    if intuitive and judging:
        if R <= 2: return "butterfly"
        elif R <= 4: return "rocket"
        else: return "eagle"
    elif intuitive and not judging:
        if R <= 3: return "dolphin"
        else: return "rocket"
    elif not intuitive and judging:
        if R <= 2: return "squirrel"
        elif R <= 4: return "turtle"
        else: return "hunter"
    else:
        if R <= 2: return "hedgehog"
        elif surplus == "high": return "turtle"
        else: return "squirrel"

