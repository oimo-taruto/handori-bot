def make_buttons(text, choices):
    """
    choices = [("ラベル", "postback_data"), ...]
    """
    actions = [
        PostbackAction(label=label, data=data, display_text=label)
        for label, data in choices
    ]
    return TemplateSendMessage(
        alt_text=text,
        template=ButtonsTemplate(
            text=text,
            actions=actions
        )
    )

